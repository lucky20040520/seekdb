"""Generate the C++ SQL tables with Python 3.12 / Unicode 15.0.0.

Use the pinned Python database image, with the repository mounted at /work:
  python /work/tools/generate_unicode_tables.py \
    --properties /work/.artifacts/unicode-15/DerivedCoreProperties.txt \
    --output /work/cpp/unicode_data.hpp

Only regeneration needs Python and the upstream data file. Normal builds and
the database runtime use the checked-in header, with no Unicode dependency.
"""
import argparse
import hashlib
from pathlib import Path
import sys
import unicodedata

VERSION = "15.0.0"
URL = "https://www.unicode.org/Public/15.0.0/ucd/DerivedCoreProperties.txt"
SHA256 = "d367290bc0867e6b484c68370530bdd1a08b6b32404601b8c7accaf83e05628d"


def ranges(values):
    result = []
    for value in sorted(values):
        if result and value == result[-1][1] + 1:
            result[-1][1] = value
        else:
            result.append([value, value])
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--properties", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if sys.version_info[:2] != (3, 12) or unicodedata.unidata_version != VERSION:
        parser.error("use the pinned Python 3.12.8 image (Unicode 15.0.0)")
    data = args.properties.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        parser.error("DerivedCoreProperties.txt does not match the pinned SHA256")
    properties = {"Cased": set(), "Case_Ignorable": set()}
    for line in data.decode("utf-8").splitlines():
        fields = line.split("#", 1)[0].split(";")
        if len(fields) != 2 or fields[1].strip() not in properties:
            continue
        bounds = [int(x, 16) for x in fields[0].strip().split("..")]
        properties[fields[1].strip()].update(range(bounds[0], bounds[-1] + 1))
    lowered, spaces, zeros = [], [], []
    for cp in range(0x110000):
        text = chr(cp)
        lower = text.lower()
        if lower != text:
            assert len(lower) <= 2
            lowered.append([cp, ord(lower[0]), ord(lower[1]) if len(lower) == 2 else 0])
        if text.isspace():
            spaces.append(cp)
        if unicodedata.decimal(text, None) == 0:
            assert [unicodedata.decimal(chr(cp + n)) for n in range(10)] == list(range(10))
            zeros.append(cp)
        assert (text.islower() or text.isupper() or text.istitle()) == (cp in properties["Cased"])
    lines = ["// Generated by tools/generate_unicode_tables.py; do not edit by hand.",
             "// Python 3.12, Unicode " + VERSION + "; see LICENSE.unicode.txt.",
             "// Cased / Case_Ignorable: " + URL, "// SHA256: " + SHA256,
             "#pragma once", "#include <cstdint>", "", "namespace mv::unicode::data {",
             'inline constexpr char version[] = "' + VERSION + '";',
             "struct Range { uint32_t first, last; };",
             "struct Lower { uint32_t source, first, second; };", ""]
    for name, values in [("cased", properties["Cased"]), ("case_ignorable", properties["Case_Ignorable"]), ("space", spaces)]:
        lines += ["inline constexpr Range " + name + "[] = {"]
        lines += ["    {0x%X, 0x%X}," % tuple(pair) for pair in ranges(values)]
        lines += ["};", ""]
    lines += ["inline constexpr uint32_t decimal_zero[] = {"]
    lines += ["    0x%X," % cp for cp in zeros]
    lines += ["};", "", "inline constexpr Lower lower[] = {"]
    lines += ["    {0x%X, 0x%X, 0x%X}," % tuple(row) for row in lowered]
    lines += ["};", "}", ""]
    args.output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Unicode {VERSION}: {len(lowered)} lower mappings, {len(spaces)} whitespace characters, {len(zeros)*10} decimal digits")


if __name__ == "__main__":
    main()
